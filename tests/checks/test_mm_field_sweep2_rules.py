def _frame(table, field, values):
    keys = D.keys(table)
    cols = {k: "1" for k in keys}
    cols[keys[0]] = ["OK", "BAD"]
    cols[field] = values
    return {table: pd.DataFrame({f"{table}.{k}": v for k, v in cols.items()})}


def test_ids_contiguous():
    got = sorted(int(r["id"][2:]) for r in module_rules(M) if r["id"][2:].isdigit())
    assert got[-1] == 1374
    assert got[got.index(1152):] == list(range(1152, 1375))
    assert set(CASES) == {f"MM{i}" for i in range(1152, 1375)}


@pytest.mark.parametrize("check_id", list(CASES))
def test_rule_fires_on_dirty_and_passes_clean(check_id):
    table, field, values = CASES[check_id]
    rule = {**next(r for r in module_rules(M) if r["id"] == check_id), "module": M}
    assert rule["field"] == f"{table}.{field}"
    _, res = run_rule(rule, TableFrames(_frame(table, field, values), D, module=M))
    assert res.error is None, res.error
    assert res.affected_count == 1, (res.total_count, res.affected_count)
