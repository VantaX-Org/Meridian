def get_table_metadata(table_name: str) -> dict[str, dict] | None:
    """Return field metadata for a SAP table, or None if not in the dictionary."""
    return DATA_DICTIONARY.get(table_name.upper())


def get_field_metadata(table_name: str, field_name: str) -> dict | None:
    """Return metadata for a specific field, or None if not found."""
    table = DATA_DICTIONARY.get(table_name.upper())
    if table is None:
        return None
    return table.get(field_name.upper())


def get_field_description(table_name: str, field_name: str) -> str:
    """Return a human-readable description for a field, or a fallback string."""
    meta = get_field_metadata(table_name, field_name)
    if meta is None:
        return f"{table_name}.{field_name}"
    return meta["description"]


def get_valid_values(table_name: str, field_name: str) -> list | None:
    """Return the list of valid values for a field, or None if free-form."""
    meta = get_field_metadata(table_name, field_name)
    if meta is None:
        return None
    return meta.get("valid_values")


def get_standard_values(table_name: str, field_name: str) -> dict:
    """Return the standard_values mapping for a field (code -> meaning)."""
    meta = get_field_metadata(table_name, field_name)
    if meta is None:
        return {}
    return meta.get("standard_values", {})


def get_config_table(table_name: str, field_name: str) -> str | None:
    """Return the config/customising table for a field, or None."""
    meta = get_field_metadata(table_name, field_name)
    if meta is None:
        return None
    return meta.get("config_table")


def get_tables_for_process(process: str) -> list[tuple[str, str]]:
    """Return all (table, field) pairs that participate in a given business process."""
    results = []
    for table_name, fields in DATA_DICTIONARY.items():
        for field_name, meta in fields.items():
            if process in meta.get("processes", []):
                results.append((table_name, field_name))
    return results


def get_all_table_names() -> list[str]:
    """Return all table names in the data dictionary."""
    return sorted(DATA_DICTIONARY.keys())


def get_key_fields(table_name: str) -> list[str]:
    """Return the list of key fields for a table."""
    table = DATA_DICTIONARY.get(table_name.upper())
    if table is None:
        return []
    return [f for f, meta in table.items() if meta.get("key")]


def get_mandatory_fields(table_name: str) -> list[str]:
    """Return the list of mandatory fields for a table."""
    table = DATA_DICTIONARY.get(table_name.upper())
    if table is None:
        return []
    return [f for f, meta in table.items() if meta.get("mandatory")]
