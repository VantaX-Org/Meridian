#!/usr/bin/env bash
# Regenerate requirements.lock: the exact == pin of every package a fresh Python 3.12
# install of requirements.txt (plus the pytest pins CI adds) resolves to.
#
# requirements.txt stays the human-edited source (floors and caps). requirements.lock is
# passed to pip as a constraints file (-c) by every CI workflow and Dockerfile, so builds
# and test shards install the same versions until someone reruns this script.
#
# Run it after editing requirements.txt, then commit both files:
#   scripts/lock-requirements.sh            # uses python3.12 from PATH
#   PYTHON=/path/to/python3.12 scripts/lock-requirements.sh
# tests/test_requirements_lock.py fails when requirements.txt names a package the lock lacks
# or a pin falls outside requirements.txt's range.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PYTHON="${PYTHON:-python3.12}"

version="$("$PYTHON" -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
if [ "$version" != "3.12" ]; then
  echo "lock-requirements: need Python 3.12 (CI and the Docker images), got $version from $PYTHON" >&2
  exit 1
fi

venv="$(mktemp -d)"
trap 'rm -rf "$venv"' EXIT

"$PYTHON" -m venv "$venv"
"$venv/bin/python" -m pip install --quiet --upgrade pip
"$venv/bin/python" -m pip install --quiet -r "$ROOT/requirements.txt" "pytest>=8.0.0" "pytest-asyncio>=0.24.0"
"$venv/bin/python" -m pip check

{
  echo "# requirements.lock: generated by scripts/lock-requirements.sh; do not edit by hand."
  echo "# Exact pins of a fresh Python 3.12 (Linux) install of requirements.txt plus"
  echo "# \"pytest>=8.0.0\" \"pytest-asyncio>=0.24.0\". Used as a pip constraints file:"
  echo "#   pip install -r requirements.txt -c requirements.lock"
  "$venv/bin/python" -m pip freeze --exclude-editable | LC_ALL=C sort -f
} > "$ROOT/requirements.lock"

echo "lock-requirements: wrote $(grep -c '==' "$ROOT/requirements.lock") pins to requirements.lock"
