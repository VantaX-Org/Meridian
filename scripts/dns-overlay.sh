#!/usr/bin/env bash
# Write (or remove) docker-compose.dns.yml next to the compose file from MERIDIAN_DNS_1/2 in .env.
#
#   bash scripts/dns-overlay.sh <compose_dir>
#
# Containers use the host's resolver by default. Behind a corporate DNS that alone resolves the SAP
# hosts, set MERIDIAN_DNS_1 (and optionally MERIDIAN_DNS_2) in .env; this writes an overlay giving
# api and worker those resolvers, and meridian-deploy.sh / update.sh add it with -f when it exists.
# With MERIDIAN_DNS_1 unset the overlay is removed. Prints the overlay path when one is in force.
set -euo pipefail

dir="${1:?usage: dns-overlay.sh <compose_dir>}"
env_file="$dir/.env"
overlay="$dir/docker-compose.dns.yml"

# An unreadable .env (the updater sidecar cannot always read it) says nothing: keep what is there.
if [[ ! -r "$env_file" ]]; then
    [[ -f "$overlay" ]] && echo "$overlay"
    exit 0
fi
envval() { sed -n "s/^$1=//p" "$env_file" | tail -1 | tr -d '"'"'"' \r'; }
dns1=$(envval MERIDIAN_DNS_1)
dns2=$(envval MERIDIAN_DNS_2)

if [[ -z "$dns1" ]]; then
    rm -f "$overlay"
    exit 0
fi
{
    echo "# Generated by scripts/dns-overlay.sh from MERIDIAN_DNS_1/2 in .env. Do not edit: change .env."
    echo "services:"
    for svc in api worker; do
        echo "  ${svc}:"
        echo "    dns:"
        echo "      - \"${dns1}\""
        if [[ -n "$dns2" ]]; then echo "      - \"${dns2}\""; fi
    done
} > "$overlay.new"
mv "$overlay.new" "$overlay"
echo "$overlay"
