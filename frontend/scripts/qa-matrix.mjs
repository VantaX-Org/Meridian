// Builds docs/qa/coverage-matrix.md from the per-route files e2e/sweep-crawl.spec.ts writes to docs/qa/crawl/.
// Every row is something the crawler really found on the page and really exercised; nothing is listed from memory.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "..", "..", "docs", "qa");
const crawl = path.join(dir, "crawl");
const files = fs.existsSync(crawl) ? fs.readdirSync(crawl).filter((f) => f.endsWith(".json")).sort() : [];
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
let total = 0, ok = 0;
const out = [];
for (const f of files) {
  const d = JSON.parse(fs.readFileSync(path.join(crawl, f), "utf8"));
  out.push(`\n### ${d.route}\n\nOpened as \`${d.url}?fixture=1\`. Uncaught errors: ${d.errors.length}.\n`);
  out.push("| Element | Kind | What it did when exercised | Covered by | Result |", "|---|---|---|---|---|");
  for (const r of d.rows) {
    total++;
    if (r.ok) ok++;
    out.push(`| ${esc(r.label) || "(no label)"}${r.target ? ` -> \`${esc(r.target)}\`` : ""} | ${r.kind} | ${esc(r.effect)} | e2e/sweep-crawl.spec.ts: sweep ${esc(d.route)} | ${r.ok ? "pass" : "FAIL"} |`);
  }
}
const head = `# Coverage matrix

Generated by \`node scripts/qa-matrix.mjs\` from the crawl in \`frontend/e2e/sweep-crawl.spec.ts\`, run in fixture mode
(\`?fixture=1\`, no backend). ${files.length} routes, ${total} elements exercised, ${ok} pass, ${total - ok} fail.

What the crawl proves: the page draws, raises no uncaught error, every internal link resolves, and every visible
button, tab and menu item in the page body does something observable when clicked. What it does not prove: that the
outcome is correct. Outcome assertions (request payloads, downloaded files, uploads, error and empty states) are in the
flow specs listed in \`docs/qa/flows.md\`. Shell controls (menus, navigation, Aletheia dock) are exercised on \`/\`.
Nothing here touches a real backend, SAP or production sign-in; docs/qa/flows.md lists what stays unproven.
`;
fs.writeFileSync(path.join(dir, "coverage-matrix.md"), head + out.join("\n") + "\n");
console.log(`${files.length} routes, ${total} elements, ${ok} pass`);
